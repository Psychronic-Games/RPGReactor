/**
 * A plugins.js the manager cannot read is never saved over. The manager kept the
 * previous project's list (or showed none) when JSON.parse threw or the strict
 * `var $plugins = [...];` pattern missed, and Save then wrote that list into the
 * project, dropping every plugin it had.
 */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const test = require('node:test');
const vm = require('node:vm');

const repoRoot = path.resolve(__dirname, '..');

function loadManager() {
    const source = fs.readFileSync(path.join(repoRoot, 'src', 'PluginManager.js'), 'utf8');
    const alerts = [];
    const PluginManager = vm.runInNewContext(`${source}\nPluginManager;`, {
        console: { log() {}, warn() {}, error() {} }, require, nw: {}, RRDialog: { alert: async text => { alerts.push(text); } },
        RRPluginAnnotations: require(path.join(repoRoot, 'src', 'utils', 'PluginAnnotations.js')),
        RRPluginParamCodec: require(path.join(repoRoot, 'src', 'utils', 'PluginParamCodec.js'))
    });
    return { PluginManager, alerts };
}

test('the manifest reader takes RPG Maker\'s file and its looser spellings', () => {
    const { PluginManager } = loadManager();
    const list = '[{"name":"A","status":true,"description":"x ] [ \\" y","parameters":{}}]';
    assert.equal(PluginManager.parsePluginsManifest(`// Generated by RPG Maker.\nvar $plugins =\n${list};\n`)[0].name, 'A');
    assert.equal(PluginManager.parsePluginsManifest(`var $plugins = ${list}`)[0].description, 'x ] [ " y', 'no semicolon, brackets in a string');
    assert.equal(PluginManager.parsePluginsManifest(`let $plugins=${list};\nconsole.log(1);`).length, 1, 'code after it');
    assert.equal(PluginManager.parsePluginsManifest('// nothing yet\n').length, 0);
    assert.throws(() => PluginManager.parsePluginsManifest('var $plugins = [{"name": "A",}];'));
    assert.throws(() => PluginManager.parsePluginsManifest('var $plugins = [{"name": "A"}'));
});

test('an unreadable plugins.js is left as it is, and no other project\'s list is saved into it', async () => {
    const { PluginManager, alerts } = loadManager();
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'rr-plugins-audit-'));
    try {
        const projectPath = path.join(root, 'Game');
        fs.mkdirSync(path.join(projectPath, 'js', 'plugins'), { recursive: true });
        const file = path.join(projectPath, 'js', 'plugins.js');
        const broken = 'var $plugins = [\n{"name":"Keep","status":true,"description":"","parameters":{}},\n];\n';
        fs.writeFileSync(file, broken);
        const manager = new PluginManager({ getCurrentProject: () => ({ path: projectPath }) });
        manager.fs = fs; manager.path = path;
        manager.renderPluginList = () => {};
        manager.scanAvailablePlugins = async () => {};
        manager.plugins = [{ name: 'FromTheLastProject', status: true, description: '', parameters: {} }];
        await manager.loadPlugins();
        assert.equal(manager.plugins.length, 0, 'the last project\'s list is gone');
        await manager.savePlugins();
        assert.equal(fs.readFileSync(file, 'utf8'), broken, 'the file is untouched');
        assert.match(alerts.at(-1), /could not be read/);
    } finally {
        fs.rmSync(root, { recursive: true, force: true });
    }
});
