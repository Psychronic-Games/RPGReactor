#!/usr/bin/env node
/**
 * Writes editor/src/legacy/RtpNames.js: the file names of RPG Maker 2000's and
 * 2003's official RTPs (read from the official installers) and, for 2000, the
 * names Don Miguel's English translation gave the same files (matched by their
 * decoded pixels or exact bytes) plus the files only his Addon has.
 *
 *   node editor/build-scripts/derive-rtp-names.cjs <rpg2000_rtp_installer.exe> <rpg2003_rtp_installer.exe> <Don Miguel RTP folder>
 *
 * The installers are at https://www.rpgmakerweb.com/run-time-package.
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { PNG } = require('pngjs');
const N = require('../src/legacy/NsisArchive.js');

const [exe2000, exe2003, donMiguel] = process.argv.slice(2);
if (!exe2000 || !exe2003 || !donMiguel) {
    console.error('usage: derive-rtp-names.cjs <rpg2000_rtp_installer.exe> <rpg2003_rtp_installer.exe> <Don Miguel RTP folder>');
    process.exit(1);
}

const stem = (name) => name.replace(/\.[^.]+$/, '');
const contentKey = (name, bytes) => {
    if (/\.png$/i.test(name)) {
        try { const png = PNG.sync.read(Buffer.from(bytes)); return 'png:' + png.width + 'x' + png.height + ':' + crypto.createHash('sha1').update(png.data).digest('hex'); } catch (_) { /* fall back to bytes */ }
    }
    return 'bin:' + crypto.createHash('sha1').update(bytes).digest('hex');
};

function official(exe) {
    const names = {}, keys = new Map();
    for (const f of N.open(fs.readFileSync(exe)).files) {
        const [folder, name] = f.path.split('/');
        if (!name || /\.(exe|ico|dll)$/i.test(name)) continue;
        (names[folder] = names[folder] || []).push(stem(name));
        keys.set(contentKey(name, f.read()), [folder, stem(name)]);
    }
    for (const folder in names) names[folder].sort();
    return { names, keys };
}

const o2000 = official(exe2000), o2003 = official(exe2003);
const renamed = {}, addon = {};
for (const folder of fs.readdirSync(donMiguel)) {
    const dir = path.join(donMiguel, folder);
    if (!fs.statSync(dir).isDirectory()) continue;
    for (const name of fs.readdirSync(dir).sort()) {
        const hit = o2000.keys.get(contentKey(name, fs.readFileSync(path.join(dir, name))));
        if (hit && hit[0] === folder) { if (hit[1] !== stem(name)) (renamed[folder] = renamed[folder] || {})[stem(name)] = hit[1]; }
        else if (!o2000.names[folder] || !o2000.names[folder].includes(stem(name))) (addon[folder] = addon[folder] || []).push(stem(name));
    }
}

const body = `/**
 * RPG Maker 2000 and 2003 RTP file names, by folder and without extension.
 * Generated by editor/build-scripts/derive-rtp-names.cjs from the official
 * installers and Don Miguel's English 2000 RTP: \`official\` is each official
 * RTP's files; \`donMiguel.renamed\` maps his names to the official file with
 * the same content; \`donMiguel.addon\` is what only his Addon has.
 */
(function(root, factory) {
    if (typeof module === 'object' && module.exports) module.exports = factory();
    else root.RRRtpNames = factory();
})(typeof globalThis !== 'undefined' ? globalThis : this, function() {
    'use strict';
    return ${JSON.stringify({ 2000: { official: o2000.names, donMiguel: { renamed, addon } }, 2003: { official: o2003.names } }, null, 1).replace(/\n/g, '\n    ')};
});
`;
const out = path.join(__dirname, '..', 'src', 'legacy', 'RtpNames.js');
fs.writeFileSync(out, body);
const count = (o) => Object.values(o).reduce((n, v) => n + (Array.isArray(v) ? v.length : Object.keys(v).length), 0);
console.log(`wrote ${out}: 2000 official ${count(o2000.names)}, 2003 official ${count(o2003.names)}, Don Miguel renamed ${count(renamed)}, addon ${count(addon)}`);
